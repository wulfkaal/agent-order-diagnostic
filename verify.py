#!/usr/bin/env python3
"""Verify the implementation and every released synthetic fixture."""
import hashlib
import subprocess
import sys
import tempfile
from pathlib import Path


ROOT = Path(__file__).resolve().parent
DIAGNOSTIC = ROOT / "order_diagnostic.py"
GENERATOR = ROOT / "generate_fixtures.py"
FIXTURES = ROOT / "fixtures"


def run(command):
    return subprocess.run(
        command,
        check=True,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
    )


def check_selftest():
    result = run([sys.executable, "-B", str(DIAGNOSTIC), "selftest"])
    if b"ordering test vector: OK\n" not in result.stdout:
        raise AssertionError("ordering test vector did not report success")
    print("selftest vectors: PASS")


def directory_bytes(path):
    return {
        item.name: item.read_bytes()
        for item in path.iterdir()
        if item.is_file()
    }


def check_manifest(path):
    lines = (path / "MANIFEST.sha256").read_text(encoding="utf-8").splitlines()
    listed = set()
    for line in lines:
        digest, filename = line.split("  ", 1)
        if filename in listed:
            raise AssertionError(f"duplicate manifest entry: {filename}")
        listed.add(filename)
        actual = hashlib.sha256((path / filename).read_bytes()).hexdigest()
        if actual != digest:
            raise AssertionError(f"manifest digest mismatch: {filename}")

    fixture_files = {
        item.name
        for item in path.iterdir()
        if item.is_file() and item.name != "MANIFEST.sha256"
    }
    if listed != fixture_files:
        raise AssertionError("manifest file list does not match fixture file list")
    return len(lines)


def check_regeneration():
    with tempfile.TemporaryDirectory() as temporary:
        regenerated = Path(temporary) / "fixtures"
        run([sys.executable, "-B", str(GENERATOR), str(regenerated)])
        released_bytes = directory_bytes(FIXTURES)
        regenerated_bytes = directory_bytes(regenerated)
        if released_bytes.keys() != regenerated_bytes.keys():
            raise AssertionError("regenerated fixture file list differs from release")
        for filename, expected in released_bytes.items():
            if regenerated_bytes[filename] != expected:
                raise AssertionError(f"regenerated bytes differ: {filename}")
        count = check_manifest(regenerated)
    check_manifest(FIXTURES)
    print(f"fixture regeneration: PASS ({len(released_bytes)} files)")
    print(f"manifest: PASS ({count} fixture hashes)")


def check_diagnostics():
    inputs = sorted(FIXTURES.glob("*.input.json"))
    if len(inputs) != 9:
        raise AssertionError(f"expected 9 inputs, found {len(inputs)}")
    for input_path in inputs:
        expected_path = input_path.with_name(
            input_path.name.replace(".input.json", ".expected.json")
        )
        result = run(
            [sys.executable, "-B", str(DIAGNOSTIC), "run", str(input_path)]
        )
        if result.stdout != expected_path.read_bytes():
            raise AssertionError(f"diagnostic output differs: {input_path.name}")
    print("diagnostic outputs: PASS (9 of 9)")


def main():
    check_selftest()
    check_regeneration()
    check_diagnostics()
    print("verify: PASS")


if __name__ == "__main__":
    try:
        main()
    except (AssertionError, OSError, subprocess.CalledProcessError) as error:
        print(f"verify: FAIL: {error}", file=sys.stderr)
        raise SystemExit(1)
